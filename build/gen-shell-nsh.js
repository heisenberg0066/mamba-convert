'use strict';
// Generates build/installer.nsh: per-user Explorer context-menu entries ("Mamba Convert" → radial wheel)
// for every supported input extension + folders, and the matching uninstall cleanup.
const fs = require('fs'); const path = require('path');
const F = require('../src/engine/formats');
const exts = [...new Set([...F.IMAGE_IN, ...F.VIDEO_IN, ...F.AUDIO_IN, ...F.PDF_IN, ...F.EBOOK_IN, ...F.DOC_IN, ...F.DATA_IN])].sort();
const key = (e) => `Software\\Classes\\SystemFileAssociations\\.${e}\\shell\\MambaConvert`;
const verb = (k) => [
  `  WriteRegStr HKCU "${k}" "MUIVerb" "Mamba Convert"`,
  `  WriteRegStr HKCU "${k}" "Icon" "$INSTDIR\\Mamba Convert.exe,0"`,
  `  WriteRegStr HKCU "${k}" "MultiSelectModel" "Player"`,
  `  WriteRegStr HKCU "${k}\\command" "" '"$INSTDIR\\Mamba Convert.exe" --radial "%1"'`,
].join('\n');
const out = `; GENERATED by build/gen-shell-nsh.js — do not edit by hand.
; Mamba Convert Explorer integration (per user, HKCU): right-click → "Mamba Convert" opens the radial wheel.
; ${exts.length} file types + folders. Removed again by the uninstaller.

!macro customInstall
${exts.map((e) => verb(key(e))).join('\n')}
${verb('Software\\Classes\\Directory\\shell\\MambaConvert')}
  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend

!macro customUnInstall
${exts.map((e) => `  DeleteRegKey HKCU "${key(e)}"`).join('\n')}
  DeleteRegKey HKCU "Software\\Classes\\Directory\\shell\\MambaConvert"
  DeleteRegValue HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Run" "MambaConvert"
  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend
`;
fs.writeFileSync(path.join(__dirname, 'installer.nsh'), out);
console.log(`installer.nsh: ${exts.length} extensions`);
module.exports = { exts };
